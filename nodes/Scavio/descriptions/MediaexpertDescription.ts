import type { INodeProperties } from 'n8n-workflow';

const show = (operation: string[], extra: Record<string, string[]> = {}) => ({
	show: { resource: ['mediaexpert'], operation, ...extra },
});

// Media Expert, 13 operations, billed on actual cost: 1 to 3 credits per call (credits_used in
// each response). One store: mediaexpert.pl (Poland, PLN), so there is no Country. Calls can
// queue behind the backend's upstream limit, so every operation carries a 240s timeout, like
// Argos.
// emptyBody: a base body {} so operations with only optional inputs still post JSON.
const request = (url: string, emptyBody = false) => ({
	request: { method: 'POST' as const, url, timeout: 240000, ...(emptyBody ? { body: {} } : {}) },
});

